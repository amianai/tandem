/*
 * Legenda comune a tutti i livelli:
 *
 *   '#' muro          '=' piattaforma attraversabile dal basso
 *   '1' '2' spawn     '*' gemma          'F' bandiera (ci dovete arrivare vivi in due)
 *   'p' 'q' 'r'       piastre pesanti: si abbassano col peso TOTALE >= 0.6
 *   'x' 'y' 'z'       fornelli (vedi `braziers`): uno scoppio vicino li accende
 *   'M' 'N' 'O' 'P'   magli (vedi `hammers`); una piastra in `links` li blocca
 *   'Z' Scoriatore    (nemico)
 *   'G' 'H' 'I'       cancelli, collegati a piastre e fornelli da `links`
 *   'X' solaio fragile (solo lo Schianto di GHISA lo sfonda)
 *   'L' muro di loppa  (solo lo scoppio di una brace lo abbatte)
 *   'T' lamiera        (cede sotto chi è pesante)
 *   '~' scoria         (superficie della vasca: sotto deve essere vuoto)
 *   '<' '>' sfiato di vapore, nel verso del getto
 *   'U' colonna d'aria (solleva solo chi è leggero)
 *   'K' forgia         (checkpoint)      'C' cassa (0,35)   'D' lingotto (0,6)
 *   'a'..'o' punti con un suggerimento (`hints`); la scenografia ci mette un cartello,
 *            quindi questi caratteri non vanno usati per altro
 *
 * I marker non sono nella legenda delle celle: i blocchi che appaiono e
 * spariscono li gestiscono le classi in `elements.ts` e `hazards.ts`.
 */

